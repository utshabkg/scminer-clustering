"""LaTeX tables from the results summary pivots (Rhea's R-2).

Usage: python scripts/make_paper_tables.py   (after the summary CSVs are refreshed)
Reads docs/author_data_results_summary.csv and docs/our_preprocessing_results_summary.csv
and writes latex/tables/r2_author_data.tex and latex/tables/r2_our_preprocessing.tex.
Standard library only, so it runs without the project environment.
"""
import csv
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

# Datasets in order of cell count, as in Table a2_reproduction.
DATASETS = {"yan": "Yan", "goolam": "Goolam", "buettner": "Buettner", "pollen": "Pollen",
            "chung": "Chung", "usoskin": "Usoskin", "kolodziejczyk": "Kolodziejczyk",
            "klein": "Klein", "zeisel": "Zeisel", "pbmc14k": "PBMC14K", "allen_100k": "Allen 100k"}
GENES = {"2000 HVG cell_ranger": "HVG cell\\_ranger", "2000 HVG seurat": "HVG seurat",
         "2000 HVG seurat_v3": "HVG seurat\\_v3", "all genes": "All genes"}
METHODS = ["hierarchical", "k-means", "Leiden (Scanpy)", "MICA"]

TABLES = {
    "author_data": dict(
        caption="ARI on the authors' released inputs, as the mean of three seeds. Each method is scored "
                "under the paper's rule, where the true number of types is given and the labels pick the "
                "setting. HVG columns use the 2,000 most variable genes chosen by the named Scanpy flavor. "
                "Hier.\\ is hierarchical clustering and Leid.\\ is PCA + Leiden. The best score for each "
                "dataset and gene setting is in bold.",
        note=""),
    "our_preprocessing": dict(
        caption="ARI on our own preprocessing of the raw data, scored and laid out as in "
                "Table~\\ref{tab:r2_author_data}.",
        note="Allen 100k is 100,000 cells drawn at random from the Allen brain atlas, scored against its "
             "34 cell classes, with a single run (seed 0). -- marks a method or gene setting not run."),
}

def read_summary(path):
    """Return {(dataset, genes): {method: ari or None}} from a two-row-header pivot export."""
    rows = list(csv.reader(open(path)))
    header = rows[1]
    out = {}
    for r in rows[2:]:
        cells = dict(zip(header, r))
        out[(r[0], r[1])] = {m: float(cells[m]) if cells[m] else None for m in METHODS}
    return out


def render(name, caption, note, data):
    label = f"tab:r2_{name}"
    unknown = {k[0] for k in data} - set(DATASETS)
    if unknown:
        raise SystemExit(f"add a display name for {sorted(unknown)}")
    datasets = [d for d in DATASETS if any(k[0] == d for k in data)]
    genes = [g for g in GENES if any(k[1] == g for k in data)]
    n = len(METHODS)
    groups = " & ".join(f"\\multicolumn{{{n}}}{{c}}{{{GENES[g]}}}" for g in genes)
    rules = "".join(f"\\cmidrule(lr){{{2 + i * n}-{1 + (i + 1) * n}}}" for i in range(len(genes)))
    lines = [
        "% Generated by scripts/make_paper_tables.py. Edit the script, not this file.",
        "\\begin{table*}[t]",
        "\\centering",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{2.5pt}",
        "\\begin{tabular}{l" + "cccc" * len(genes) + "}",
        "\\toprule",
        f" & {groups} \\\\",
        rules,
        "Dataset" + " & Hier. & $k$-means & Leid. & MICA" * len(genes) + " \\\\",
        "\\midrule",
    ]
    for d in datasets:
        cells = []
        for g in genes:
            scores = data.get((d, g), dict.fromkeys(METHODS))
            present = [f"{v:.3f}" for v in scores.values() if v is not None]
            best = max(present, key=float) if present else None
            for m in METHODS:
                v = scores[m]
                if v is None:
                    cells.append("--")
                else:
                    cells.append(f"\\textbf{{{v:.3f}}}" if f"{v:.3f}" == best else f"{v:.3f}")
        lines.append(f"{DATASETS[d]} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    if note:
        lines += ["\\\\[2pt]", f"\\parbox{{\\textwidth}}{{\\scriptsize {note}}}"]
    lines.append("\\end{table*}")
    return "\n".join(lines) + "\n"

def main():
    for name, spec in TABLES.items():
        data = read_summary(REPO / "docs" / f"{name}_results_summary.csv")
        out = REPO / "latex" / "tables" / f"r2_{name}.tex"
        out.write_text(render(name, spec["caption"], spec["note"], data))
        print(f"wrote {out.relative_to(REPO)}")


if __name__ == "__main__":
    main()
