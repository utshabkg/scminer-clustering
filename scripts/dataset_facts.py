"""Every number a dataset card needs, read straight from the processed files (L-1 to L-3).

Usage: python scripts/dataset_facts.py [dataset ...]
With no arguments it covers every dataset we have processed. Writes
docs/dataset_facts.md and docs/dataset_facts.csv, so the dataset cards can be
filled in without anyone having to run Python. Rerun it whenever preprocessing
changes, and the numbers in the cards can be checked against it.

For each dataset it reports the cell and gene counts before and after our
filtering, how the labels are distributed, the sequencing depth, and the exact
preprocessing settings that produced the file.
"""
import sys

import anndata as ad
import numpy as np
import pandas as pd
from scipy import sparse

from scminer_clust.paths import PROCESSED, REPO

SKIP = ("_exchange", "mi_reference")


def counts(a):
    """Raw counts if we kept them, else undo the log transform."""
    if "counts" in a.layers:
        return a.layers["counts"]
    base = a.uns.get("log1p", {}).get("base", 2)
    X = a.X.copy()
    if sparse.issparse(X):
        X.data = np.power(float(base), X.data) - 1
    else:
        X = np.power(float(base), X) - 1
    return X


def facts(name):
    a = ad.read_h5ad(PROCESSED / f"{name}.h5ad")
    qc = a.uns.get("qc", {})
    lab = pd.Series(a.obs["label"]).astype(str)
    vc = lab.value_counts()
    C = counts(a)
    per_cell = np.asarray(C.sum(1)).ravel()
    detected = np.asarray((C > 0).sum(1)).ravel()
    row = {
        "dataset": name,
        "cells_after_filtering": int(a.n_obs),
        "cells_before_filtering": int(qc.get("cells_before", np.nan)) if qc.get("cells_before") else "",
        "genes_after_filtering": int(a.n_vars),
        "genes_before_filtering": int(qc.get("genes_before", np.nan)) if qc.get("genes_before") else "",
        "label_classes": int(lab.nunique()),
        "largest_class": f"{vc.index[0]} ({vc.iloc[0]})",
        "smallest_class": f"{vc.index[-1]} ({vc.iloc[-1]})",
        "smallest_class_percent": round(100 * vc.iloc[-1] / a.n_obs, 1),
        "median_counts_per_cell": int(np.median(per_cell)),
        "median_genes_detected_per_cell": int(np.median(detected)),
        "percent_zeros": round(100 * float(1 - (C > 0).sum() / (a.n_obs * a.n_vars)), 1),
        "normalization": a.uns.get("normalization", "log2(CPM + 1)"),
        "qc_rule": f"{qc.get('nmads', 4)} MADs on log counts and log genes" if qc else "as released by the scMINER authors",
        "mito_filter": "off" if not qc.get("mito_nmads") else f"{qc.get('mito_nmads')} MADs",
    }
    return row, vc


def main(names=None):
    names = names or sorted(p.stem for p in PROCESSED.glob("*.h5ad")
                            if not any(s in p.stem for s in SKIP))
    rows, blocks = [], []
    for n in names:
        try:
            row, vc = facts(n)
        except Exception as e:  # a dataset we have not processed yet should not stop the rest
            print(f"  skipped {n}: {e}")
            continue
        rows.append(row)
        table = "\n".join(f"| {k} | {v} | {100 * v / row['cells_after_filtering']:.1f}% |" for k, v in vc.items())
        blocks.append(
            f"### {n}\n\n"
            f"- Cells: {row['cells_before_filtering'] or 'as released'} before our filtering, "
            f"**{row['cells_after_filtering']}** after\n"
            f"- Genes: {row['genes_before_filtering'] or 'as released'} before, **{row['genes_after_filtering']}** after\n"
            f"- Quality control: {row['qc_rule']}. Mitochondrial filter: {row['mito_filter']}\n"
            f"- Normalization: {row['normalization']}\n"
            f"- Depth: median {row['median_counts_per_cell']:,} counts and "
            f"{row['median_genes_detected_per_cell']:,} detected genes per cell. "
            f"{row['percent_zeros']}% of the matrix is zero\n"
            f"- Labels: {row['label_classes']} classes, smallest is {row['smallest_class']} "
            f"= {row['smallest_class_percent']}% of cells\n\n"
            f"| Label | Cells | Share |\n|---|---|---|\n{table}\n")
        print(f"  {n}: {row['cells_after_filtering']} cells, {row['genes_after_filtering']} genes, "
              f"{row['label_classes']} classes")
    df = pd.DataFrame(rows)
    df.to_csv(REPO / "docs" / "dataset_facts.csv", index=False)
    header = (
        "# Dataset facts\n\n"
        "Generated by `scripts/dataset_facts.py` from the processed files, so these are the exact\n"
        "numbers our experiments used. Do not edit by hand. Rerun the script after any change to\n"
        "preprocessing, and use these values when filling in the dataset cards.\n\n"
        "`paper_*` are the inputs the scMINER authors released, which we use for every comparison\n"
        "against their published scores. The others are the same data put through our own pipeline.\n\n"
        "## Summary\n\n" + df.to_markdown(index=False) + "\n\n## Per dataset\n\n")
    (REPO / "docs" / "dataset_facts.md").write_text(header + "\n".join(blocks))
    print(f"wrote docs/dataset_facts.md and docs/dataset_facts.csv for {len(rows)} datasets")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:] or None))
